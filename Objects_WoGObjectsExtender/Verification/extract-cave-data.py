from pathlib import Path
import re
import json

root = Path(__file__).resolve().parent.parent
source = Path('D:/games/HoMM 3 ERA/Mods/WoG Scripts/Data/s/48 wog - adventure cave.erm').read_text(encoding='utf-8-sig')
obstacles = source.split('!?FU736;', 1)[1].split('!?FU737;', 1)[0]
positions = source.split('!?FU737;', 1)[1].split('!?FU738;', 1)[0]
commands = []
slots = []
for kind in range(1, 11):
    def section(text):
        match = re.search(r'!!(?:if|el)&i\^wog_30_advCaveBattleType\^=' + str(kind) + r';(.*?)(?=!!el&|!!en;)', text, re.S)
        assert match, kind
        return match.group(1)
    commands.append('BF:C;' + ''.join('BF:' + command + ';' for command in re.findall(r'!!BF:([^;]+);', section(obstacles))))
    row = re.search(r'!!FU738[^;]*:P([\d/]+);', section(positions))
    assert row, kind
    values = list(map(int, row.group(1).split('/')))
    assert len(values) == 14
    slots.append(values)

prices = Path('D:/games/HoMM 3 ERA/Mods/WoG Scripts/Data/s/50 wog - school of wizardry.erm').read_text(encoding='utf-8-sig')
spell_prices = {int(spell):int(price) for spell,price in re.findall(r'!!VRv1&x1=(\d+):S(\d+);', prices)}
assert len(spell_prices) == 70
text = '#pragma once\n// Generated by Verification/extract-cave-data.py from source ERM numeric tables.\nnamespace wog { namespace cave_data {\n'
layouts=[]
for command in commands:
    layout=[(int(obj),int(hex)) for obj,hex in re.findall(r'O(\d+)/(\d+)',command)]
    for mask in re.findall(r'BF:M([^;]+);',command):
        values=list(map(int,mask.split('/')))
        obstacle=values[11] if len(values)>11 else 0x54
        layout.extend((obstacle,row*17+column) for row,bits in enumerate(values[:11])
                      for column in range(17) if bits & (1<<column))
    assert layout and all(0<=obj<=90 and 0<=hex<187 for obj,hex in layout)
    layouts.append(layout)
text += 'struct Obstacle { int object, hex; };\n'
for index,layout in enumerate(layouts):
    text += 'static const Obstacle field%d[] = {\n    '%index + ','.join('{%d,%d}'%pair for pair in layout) + '\n};\n'
text += 'struct Battlefield { const Obstacle *entries; unsigned count; };\n'
text += 'static const Battlefield battlefields[10] = {\n' + ',\n'.join(
    '    {field%d, sizeof(field%d)/sizeof(Obstacle)}'%(i,i) for i in range(10))+'\n};\n'

text += 'static const int positions[10][14] = {\n' + ',\n'.join('    {'+','.join(map(str,row))+'}' for row in slots) + '\n};\n'
text += 'static const int schoolSpellPrices[70] = {\n    ' + ','.join(str(spell_prices[i]) for i in range(70))+'\n};\n} }\n'
target = root / 'WoGObjectCaveData.h'
target.write_text(text, encoding='utf-8', newline='')
print('Extracted 10 obstacle layouts, 140 battle positions and 70 spell prices:', target)
